-- 1. Ensure 'users' table has all required columns and constraints
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT,
    college_name TEXT,
    branch TEXT,
    academic_year TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    role TEXT DEFAULT 'user'
);

-- In case 'users' table already exists with only some columns, add missing ones safely:
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS password_hash TEXT;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS college_name TEXT;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS branch TEXT;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS academic_year TEXT;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ DEFAULT NOW();
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS role TEXT DEFAULT 'user';

-- 2. Create 'profiles' table
CREATE TABLE IF NOT EXISTS public.profiles (
    user_id BIGINT PRIMARY KEY,
    technical_skills JSONB DEFAULT '[]'::jsonb,
    interests JSONB DEFAULT '[]'::jsonb,
    preferred_career TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create 'assessments' table
CREATE TABLE IF NOT EXISTS public.assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    taken_at TIMESTAMPTZ DEFAULT NOW(),
    recommended_career TEXT NOT NULL,
    alternative_career TEXT,
    score_total INTEGER NOT NULL,
    percentage_total NUMERIC NOT NULL,
    domain_scores_json JSONB NOT NULL,
    explanation TEXT NOT NULL,
    question_ids_json JSONB NOT NULL
);

-- 4. Create 'roadmap_progress' table
CREATE TABLE IF NOT EXISTS public.roadmap_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    career_domain TEXT NOT NULL,
    task_id TEXT NOT NULL,
    completed INTEGER DEFAULT 0,
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(user_id, career_domain, task_id)
);

-- ==============================================================================
-- 5. Row-Level Security (RLS) Configuration
-- Enables your publishable API key (anon) to insert student form submissions
-- and query records without "new row violates row-level security policy" errors.
-- ==============================================================================

-- Enable RLS on all tables
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.assessments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.roadmap_progress ENABLE ROW LEVEL SECURITY;

-- Allow public (anon / publishable API key) INSERT & SELECT on users
DROP POLICY IF EXISTS "Allow student registration insert" ON public.users;
CREATE POLICY "Allow student registration insert" ON public.users
    FOR INSERT TO anon, authenticated
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow student select" ON public.users;
CREATE POLICY "Allow student select" ON public.users
    FOR SELECT TO anon, authenticated
    USING (true);

-- Allow public INSERT, UPDATE, SELECT on profiles
DROP POLICY IF EXISTS "Allow student profile upsert" ON public.profiles;
CREATE POLICY "Allow student profile upsert" ON public.profiles
    FOR ALL TO anon, authenticated
    USING (true)
    WITH CHECK (true);

-- Allow public INSERT & SELECT on assessments
DROP POLICY IF EXISTS "Allow student assessment insert" ON public.assessments;
CREATE POLICY "Allow student assessment insert" ON public.assessments
    FOR ALL TO anon, authenticated
    USING (true)
    WITH CHECK (true);

-- Allow public INSERT, UPDATE, SELECT on roadmap_progress
DROP POLICY IF EXISTS "Allow roadmap progress updates" ON public.roadmap_progress;
CREATE POLICY "Allow roadmap progress updates" ON public.roadmap_progress
    FOR ALL TO anon, authenticated
    USING (true)
    WITH CHECK (true);
